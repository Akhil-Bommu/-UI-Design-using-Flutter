1(a) Install Flutter and Dart SDK
Aim

To install and configure the Flutter and Dart SDK and verify the development environment.

Procedure
Download and install the Flutter SDK.
Extract Flutter to a suitable location, for example:
C:\src\flutter
Add Flutter's bin folder to the system PATH.
Install Android Studio or another supported IDE.
Install Android SDK and required tools.
Create/configure an emulator or connect a physical Android device.


Open Command Prompt and run:
flutter doctor




Important Commands
flutter --version
dart --version
flutter doctor
flutter devices
Flutter and Dart SDK were successfully installed and the development environment was configured.
